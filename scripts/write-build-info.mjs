#!/usr/bin/env node
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
let commit = process.env.BLANK_CLOUD_COMMIT?.trim() || "";
if (!commit) {
  try {
    commit = execSync("git rev-parse HEAD", { cwd: root, encoding: "utf8" }).trim();
  } catch {
    commit = "unknown";
  }
}
const version = pkg.version ?? "0.0.0";
const out = path.join(root, "src/build-info.generated.ts");
fs.writeFileSync(
  out,
  `/** Generated by scripts/write-build-info.mjs — do not edit */\nexport const BUILD_INFO = {\n  version: ${JSON.stringify(version)},\n  commit: ${JSON.stringify(commit)},\n} as const;\n`,
);
