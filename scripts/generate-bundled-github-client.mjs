#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcFile = path.join(root, "github-oauth-client-id");
const outFile = path.join(root, "src/auth/bundled-client-id.generated.ts");

function readClientId(filePath) {
  try {
    const lines = fs.readFileSync(filePath, "utf8").split(/\r?\n/);
    for (const line of lines) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      if (/REPLACE|CHANGEME|PASTE/i.test(t)) continue;
      return t;
    }
  } catch {
    /* missing file ok */
  }
  return "";
}

const id = readClientId(srcFile);
fs.writeFileSync(
  outFile,
  `/** Auto-generated by scripts/generate-bundled-github-client.mjs — do not edit */\nexport const BUNDLED_GITHUB_OAUTH_CLIENT_ID = ${JSON.stringify(id)};\n`,
);
console.log(
  id
    ? `bundled GitHub OAuth client id: ${id.slice(0, 8)}…`
    : "bundled GitHub OAuth client id: (empty — add github-oauth-client-id for Connect GitHub)",
);
