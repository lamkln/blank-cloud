import fs from "node:fs";
import path from "node:path";
import { resolveWorkspacePath, writeWorkspaceFile } from "../workspace/paths.js";
import type { FabricVersionsResolved } from "./fabric-meta.js";
import { resolveFabricApiVersion } from "./fabric-meta.js";
import { installGradleWrapper } from "./gradle-wrapper.js";

export interface FabricScaffoldOptions {
  modId: string;
  modName: string;
  projectPath: string;
  versions: FabricVersionsResolved;
}

function pkg(modId: string): string {
  const safe = modId.replace(/[^a-z0-9_]/gi, "_").toLowerCase();
  return `com.blankcloud.${safe}`;
}

function pkgPath(modId: string): string {
  return pkg(modId).replace(/\./g, "/");
}

/** 1x1 red PNG */
const RUBY_PNG = Buffer.from(
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==",
  "base64",
);


export async function scaffoldFabricRubyMod(opts: FabricScaffoldOptions): Promise<{
  projectPath: string;
  fabricApi: string;
  files: string[];
}> {
  const { modId, modName, projectPath, versions } = opts;
  const fabricApi = await resolveFabricApiVersion(versions.minecraft);
  const javaPkg = pkg(modId);
  const javaPath = pkgPath(modId);
  const base = projectPath.replace(/\/$/, "");
  const files: string[] = [];

  const w = (rel: string, content: string) => {
    const full = `${base}/${rel}`;
    writeWorkspaceFile(full, content);
    files.push(full);
  };
  const wb = (rel: string, buf: Buffer) => {
    const full = `${base}/${rel}`;
    const abs = resolveWorkspacePath(full);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, buf);
    files.push(full);
  };

  w(
    "gradle.properties",
    `org.gradle.jvmargs=-Xmx2G
minecraft_version=${versions.minecraft}
yarn_mappings=${versions.yarn}
loader_version=${versions.loader}
fabric_version=${fabricApi}
mod_version=1.0.0
maven_group=${javaPkg}
archives_base_name=${modId}
`,
  );

  w(
    "settings.gradle",
    `pluginManagement {
    repositories {
        maven { url = 'https://maven.fabricmc.net/' }
        gradlePluginPortal()
        mavenCentral()
    }
}
`,
  );

  w(
    "build.gradle",
    `plugins {
    id 'fabric-loom' version '${versions.loom}'
    id 'maven-publish'
    id 'java'
}

version = project.mod_version
group = project.maven_group

base {
    archivesName = project.archives_base_name
}

repositories {
    mavenCentral()
}

dependencies {
    minecraft "com.mojang:minecraft:\${project.minecraft_version}"
    mappings "net.fabricmc:yarn:\${project.yarn_mappings}:v2"
    modImplementation "net.fabricmc:fabric-loader:\${project.loader_version}"
    modImplementation "net.fabricmc.fabric-api:fabric-api:\${project.fabric_version}"
}

processResources {
    inputs.property "version", project.version
    filesMatching("fabric.mod.json") {
        expand "version": project.version
    }
}

tasks.withType(JavaCompile).configureEach {
    it.options.release = 21
}

java {
    withSourcesJar()
    sourceCompatibility = JavaVersion.VERSION_21
    targetCompatibility = JavaVersion.VERSION_21
}
`,
  );

  w(
    "src/main/resources/fabric.mod.json",
    JSON.stringify(
      {
        schemaVersion: 1,
        id: modId,
        version: "${version}",
        name: modName,
        description: `${modName} — generated by blank-cloud Mod Maker`,
        authors: ["blank-cloud"],
        contact: {},
        license: "MIT",
        icon: "assets/" + modId + "/icon.png",
        environment: "*",
        entrypoints: {
          main: [`${javaPkg}.RubyMod`],
        },
        depends: {
          fabricloader: ">=0.16.0",
          minecraft: `~${versions.minecraft}`,
          java: ">=21",
          fabric: "*",
        },
      },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/assets/${modId}/lang/en_us.json`,
    JSON.stringify(
      {
        [`block.${modId}.ruby_ore`]: "Ruby Ore",
        [`item.${modId}.ruby_gem`]: "Ruby Gem",
        [`item.${modId}.ruby_sword`]: "Ruby Sword",
      },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/assets/${modId}/blockstates/ruby_ore.json`,
    JSON.stringify({ variants: { "": { model: `${modId}:block/ruby_ore` } } }, null, 2),
  );

  w(
    `src/main/resources/assets/${modId}/models/block/ruby_ore.json`,
    JSON.stringify(
      {
        parent: "minecraft:block/cube_all",
        textures: { all: `${modId}:block/ruby_ore` },
      },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/assets/${modId}/models/item/ruby_gem.json`,
    JSON.stringify(
      { parent: "minecraft:item/generated", textures: { layer0: `${modId}:item/ruby_gem` } },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/assets/${modId}/models/item/ruby_sword.json`,
    JSON.stringify(
      { parent: "minecraft:item/handheld", textures: { layer0: `${modId}:item/ruby_sword` } },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/data/${modId}/loot_table/blocks/ruby_ore.json`,
    JSON.stringify(
      {
        type: "minecraft:block",
        pools: [
          {
            rolls: 1,
            entries: [
              {
                type: "minecraft:item",
                name: `${modId}:ruby_gem`,
                functions: [
                  {
                    function: "minecraft:apply_bonus",
                    enchantment: "minecraft:fortune",
                    formula: "ore_drops",
                  },
                  { function: "minecraft:explosion_decay" },
                ],
              },
            ],
          },
        ],
      },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/data/${modId}/recipe/ruby_sword.json`,
    JSON.stringify(
      {
        type: "minecraft:crafting_shaped",
        pattern: [" R ", " R ", " S "],
        key: {
          R: { item: `${modId}:ruby_gem` },
          S: { item: "minecraft:stick" },
        },
        result: { id: `${modId}:ruby_sword`, count: 1 },
      },
      null,
      2,
    ),
  );

  wb(`src/main/resources/assets/${modId}/textures/block/ruby_ore.png`, RUBY_PNG);
  wb(`src/main/resources/assets/${modId}/textures/item/ruby_gem.png`, RUBY_PNG);
  wb(`src/main/resources/assets/${modId}/textures/item/ruby_sword.png`, RUBY_PNG);
  wb(`src/main/resources/assets/${modId}/icon.png`, RUBY_PNG);

  w(
    `src/main/java/${javaPath}/RubyMod.java`,
    `package ${javaPkg};

import net.fabricmc.api.ModInitializer;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

public class RubyMod implements ModInitializer {
    public static final String MOD_ID = "${modId}";
    public static final Logger LOGGER = LoggerFactory.getLogger(MOD_ID);

    @Override
    public void onInitialize() {
        ModBlocks.register();
        ModItems.register();
        ModWorldGen.register();
        LOGGER.info("${modName} loaded");
    }
}
`,
  );

  w(
    `src/main/java/${javaPath}/ModBlocks.java`,
    `package ${javaPkg};

import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.ExperienceDroppingBlock;
import net.minecraft.block.MapColor;
import net.minecraft.item.BlockItem;
import net.minecraft.item.Item;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.util.Identifier;
import net.minecraft.util.math.intprovider.UniformIntProvider;

public class ModBlocks {
    public static final Block RUBY_ORE = new ExperienceDroppingBlock(
            UniformIntProvider.create(2, 6),
            AbstractBlock.Settings.create().mapColor(MapColor.RED).strength(3.0f, 3.0f).requiresTool()
    );

    public static void register() {
        registerBlock("ruby_ore", RUBY_ORE);
    }

    private static void registerBlock(String name, Block block) {
        Registry.register(Registries.BLOCK, Identifier.of(RubyMod.MOD_ID, name), block);
        Registry.register(Registries.ITEM, Identifier.of(RubyMod.MOD_ID, name),
                new BlockItem(block, new Item.Settings()));
    }
}
`,
  );

  w(
    `src/main/java/${javaPath}/ModItems.java`,
    `package ${javaPkg};

import net.minecraft.item.Item;
import net.minecraft.item.SwordItem;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.util.Identifier;

public class ModItems {
    public static final Item RUBY_GEM = new Item(new Item.Settings());
    public static final SwordItem RUBY_SWORD = new SwordItem(
            ModToolMaterials.RUBY,
            new Item.Settings()
    );

    public static void register() {
        registerItem("ruby_gem", RUBY_GEM);
        registerItem("ruby_sword", RUBY_SWORD);
    }

    private static void registerItem(String name, Item item) {
        Registry.register(Registries.ITEM, Identifier.of(RubyMod.MOD_ID, name), item);
    }
}
`,
  );

  w(
    `src/main/java/${javaPath}/ModToolMaterials.java`,
    `package ${javaPkg};

import net.minecraft.item.ToolMaterial;
import net.minecraft.registry.tag.BlockTags;
import net.minecraft.registry.tag.TagKey;
import net.minecraft.item.Item;
import net.minecraft.block.Block;
import net.minecraft.recipe.Ingredient;
import net.minecraft.util.Identifier;
import net.minecraft.registry.Registries;

public class ModToolMaterials {
    public static final ToolMaterial RUBY = new ToolMaterial() {
        @Override
        public int getDurability() {
            return 500;
        }

        @Override
        public float getMiningSpeedMultiplier() {
            return 6.0f;
        }

        @Override
        public float getAttackDamage() {
            return 3.0f;
        }

        @Override
        public TagKey<Block> getInverseTag() {
            return BlockTags.INCORRECT_FOR_IRON_TOOL;
        }

        @Override
        public int getEnchantability() {
            return 12;
        }

        @Override
        public Ingredient getRepairIngredient() {
            return Ingredient.ofItems(
                    Registries.ITEM.get(Identifier.of(RubyMod.MOD_ID, "ruby_gem"))
            );
        }
    };
}
`,
  );

  w(
    `src/main/resources/data/${modId}/worldgen/configured_feature/ruby_ore.json`,
    JSON.stringify(
      {
        type: "minecraft:ore",
        config: {
          discard_chance_on_air_exposure: 0,
          size: 7,
          targets: [
            {
              target: {
                predicate_type: "minecraft:tag_match",
                tag: "minecraft:stone_ore_replaceables",
              },
              state: { Name: `${modId}:ruby_ore` },
            },
          ],
        },
      },
      null,
      2,
    ),
  );

  w(
    `src/main/resources/data/${modId}/worldgen/placed_feature/ruby_ore_placed.json`,
    JSON.stringify(
      {
        feature: `${modId}:ruby_ore`,
        placement: [
          { type: "minecraft:count", count: 9 },
          { type: "minecraft:in_square" },
          {
            type: "minecraft:height_range",
            height: {
              type: "minecraft:uniform",
              max_inclusive: { absolute: 32 },
              min_inclusive: { absolute: -64 },
            },
          },
          { type: "minecraft:biome" },
        ],
      },
      null,
      2,
    ),
  );

  w(
    `src/main/java/${javaPath}/ModWorldGen.java`,
    `package ${javaPkg};

import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.util.Identifier;
import net.minecraft.world.gen.GenerationStep;
import net.minecraft.world.gen.feature.PlacedFeature;

public class ModWorldGen {
    public static final RegistryKey<PlacedFeature> RUBY_ORE_PLACED_KEY =
            RegistryKey.of(RegistryKeys.PLACED_FEATURE, Identifier.of(RubyMod.MOD_ID, "ruby_ore_placed"));

    public static void register() {
        BiomeModifications.addFeature(
                BiomeSelectors.foundInOverworld(),
                GenerationStep.Feature.UNDERGROUND_ORES,
                RUBY_ORE_PLACED_KEY
        );
    }
}
`,
  );

  w(".gitignore", "build/\n.gradle/\nrun/\n");

  await installGradleWrapper(base);

  return { projectPath: base, fabricApi, files };
}
